import {chromium} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:960},offline:true});
const errors=[], requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.url().startsWith('http'))requests.push(r.url());});
await page.goto(pathToFileURL(resolve('release/余烬守望.html')).href);await page.waitForSelector('canvas');
assert.equal(await page.evaluate(()=>typeof window.__emberwatch),'undefined');
await page.locator('[data-type="arrow"]').click();const r=await page.locator('canvas').boundingBox();await page.mouse.click(r.x+140/1100*r.width,r.y+300/740*r.height);
await page.waitForTimeout(200);assert.equal(await page.locator('#gold-value').innerText(),'280');
await page.locator('#start-button').click();await page.waitForTimeout(250);assert.match(await page.locator('#start-label').innerText(),/战斗中/);
await page.locator('[data-action="help"]').first().click();assert.match(await page.locator('.help-modal').innerText(),/守望/);await page.keyboard.press('Escape');
await page.locator('[data-action="maps"]').first().click();await page.locator('[data-action="choose-map"][data-map="2"]').click();
await page.waitForTimeout(300);assert.equal(await page.locator('#map-title').innerText(),'灰烬山隘');
await page.screenshot({path:'qa/offline-ash.png'});
assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
console.log('PASS: standalone file:// game boots offline, no network requests, debug hooks removed; construction, combat, help & map switching work.');
await browser.close();
